// `string & {}` keeps literal autocompletion while still accepting any string.
export type AudioId = MusicId | SfxId | (string & {});

/** Default crossfade between two music beds. */
export const DEFAULT_MUSIC_FADE_MS = 1800;

/** Throttle applied to one-shots that don't declare `minIntervalMs`. */
export const DEFAULT_SFX_MIN_INTERVAL_MS = 40;

const FADE_STEP_MS = 40;
const UNLOCK_EVENTS = ['pointerdown', 'keydown', 'touchstart'] as const;

export type CategoryVolumes = Record<AudioCategory, number>;
export type CategoryMutes = Record<AudioCategory, boolean>;

/**
 * Default per-category volume. Used until the persisted user preference is
 * loaded. Music is intentionally lower than SFX — a UI click should always
 * cut through the underscore.
 */
export const DEFAULT_VOLUMES: CategoryVolumes = {
  music: 0.5,
  sfx: 0.7,
};

const DEFAULT_MUTES: CategoryMutes = {
  music: false,
  sfx: false,
};

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

/**
 * Categorise an id by its `music.*` / `sfx.*` prefix. Anything that doesn't
 * carry an explicit prefix is treated as SFX so accidental ids don't compete
 * with the music bus for the master gain.
 */
function categoryForId(id: string): AudioCategory {
  return id.startsWith('music.') ? 'music' : 'sfx';
}

function clamp01(value: number): number {
  if (Number.isNaN(value)) return 0;
  return Math.max(0, Math.min(1, value));
}

function nowMs(): number {
  return typeof performance !== 'undefined' && typeof performance.now === 'function'
    ? performance.now()
    : Date.now();
}

const MIME_BY_EXT: Record<string, string> = {
  webm: 'audio/webm; codecs="opus"',
  ogg: 'audio/ogg; codecs="vorbis"',
  opus: 'audio/ogg; codecs="opus"',
  m4a: 'audio/mp4; codecs="mp4a.40.2"',
  mp3: 'audio/mpeg',
  wav: 'audio/wav',
};

const canPlayCache: Map<string, boolean> = new Map();

/** True when the browser claims it can decode the container/codec of `src`. */
function canPlaySrc(src: string): boolean {
  const ext = (src.split(/[?#]/)[0] ?? '').split('.').pop()?.toLowerCase() ?? '';
  const mime = MIME_BY_EXT[ext];
  if (!mime) return true; // unknown extension: let the element try.
  const cached = canPlayCache.get(mime);
  if (cached !== undefined) return cached;
  let ok = true;
  try {
    const probe = new Audio();
    ok = typeof probe.canPlayType === 'function' ? probe.canPlayType(mime) !== '' : true;
  } catch {
    ok = true;
  }
  canPlayCache.set(mime, ok);
  return ok;
}

// ---------------------------------------------------------------------------
// Manager
// ---------------------------------------------------------------------------

type CachedSound = {
  /** The actual <audio> instance — null while loading or after a hard failure. */
  audio: HTMLAudioElement | null;
  /** True when we've confirmed the file is missing / errored. Subsequent plays no-op. */
  failed: boolean;
  /** URL the element is currently pointed at. */
  src?: string;
  /** Alternative URL not tried yet (cleared once we switch to it). */
  fallback?: string;
};

export class AudioManager {
  private manifest: AudioManifest = {};
  private cache: Map<string, CachedSound> = new Map();
  private volumes: CategoryVolumes = { ...DEFAULT_VOLUMES };
  private mutes: CategoryMutes = { ...DEFAULT_MUTES };
  private warned: Set<string> = new Set();
  /** Tracks which loop-ids are currently meant to be playing, by element id. */
  private looping: Set<string> = new Set();
  /** The bed selected through `playMusic()` (null when none). */
  private currentMusic: string | null = null;
  /** Per-id fade multiplier 0..1 (absent = 1). Multiplied into the element volume. */
  private fadeGain: Map<string, number> = new Map();
  private fadeTimers: Map<string, ReturnType<typeof setInterval>> = new Map();
  /** Per-id base-volume override from the last `play(id, { volume })`. */
  private baseOverride: Map<string, number> = new Map();
  /** Timestamp of the last accepted one-shot per id (throttle). */
  private lastPlayedAt: Map<string, number> = new Map();
  /** Loops whose play() was rejected by the autoplay policy. */
  private pendingUnlock: Set<string> = new Set();
  private unlockHandler: (() => void) | null = null;

  // -------------------------------------------------------------------------
  // Manifest registration
  // -------------------------------------------------------------------------

  /** Replace the registered manifest. Existing cache entries are preserved. */
  registerManifest(manifest: AudioManifest): void {
    this.manifest = { ...manifest };
  }

  /** Register a single entry (or override an existing one). */
  register(id: string, entry: AudioManifestEntry): void {
    this.manifest[id] = entry;
  }

  hasEntry(id: string): boolean {
    return Object.prototype.hasOwnProperty.call(this.manifest, id);
  }

  // -------------------------------------------------------------------------
  // Volume / mute
  // -------------------------------------------------------------------------

  setVolume(category: AudioCategory, value: number): void {
    this.volumes[category] = clamp01(value);
    this.applyVolumeToCachedAudio(category);
  }

  getVolume(category: AudioCategory): number {
    return this.volumes[category];
  }

  setVolumes(values: Partial<CategoryVolumes>): void {
    if (typeof values.music === 'number') this.setVolume('music', values.music);
    if (typeof values.sfx === 'number') this.setVolume('sfx', values.sfx);
  }

  getVolumes(): CategoryVolumes {
    return { ...this.volumes };
  }

  mute(category: AudioCategory): void {
    this.mutes[category] = true;
    // Stop anything currently audible in that category.
    for (const [id, entry] of this.cache.entries()) {
      if (categoryForId(id) !== category) continue;
      const audio = entry.audio;
      if (audio && !audio.paused) {
        audio.pause();
      }
      // A bed that was fading out when the mute landed is simply done.
      if (this.fadeTimers.has(id)) {
        this.clearFade(id);
        if (!this.looping.has(id)) this.rewind(id);
      }
    }
  }

  unmute(category: AudioCategory): void {
    this.mutes[category] = false;
    // Re-arm any loops that were paused by mute.
    for (const id of this.looping) {
      if (categoryForId(id) !== category) continue;
      this.playLoop(id);
    }
  }

  setMuted(category: AudioCategory, muted: boolean): void {
    if (muted) this.mute(category);
    else this.unmute(category);
  }

  isMuted(category: AudioCategory): boolean {
    return this.mutes[category];
  }

  // -------------------------------------------------------------------------
  // Loading
  // -------------------------------------------------------------------------

  /**
   * Eagerly load a clip into the cache. Called automatically by `play()` /
   * `playLoop()` on first use; exposed so callers can prefetch ahead of a
   * predictable trigger (e.g. after entering the gameplay screen).
   */
  load(id: string, url?: string): void {
    if (typeof window === 'undefined') return;
    if (this.cache.has(id)) return;
    const entry = this.manifest[id];
    const src = url ?? entry?.src;
    if (!src) {
      this.warnOnce(id, `[audio] No manifest entry for "${id}"`);
      this.cache.set(id, { audio: null, failed: true });
      return;
    }
    // Pick the first encoding this browser says it can decode.
    let primary = src;
    let fallback = url ? undefined : entry?.fallback;
    if (fallback && !canPlaySrc(primary)) {
      primary = fallback;
      fallback = undefined;
    }
    try {
      const audio = new Audio(primary);
      audio.preload = 'auto';
      const cached: CachedSound = { audio, failed: false, src: primary, fallback };
      audio.addEventListener('error', () => {
        // First failure with an untried alternative: swap the source once.
        if (cached.fallback) {
          const next = cached.fallback;
          cached.fallback = undefined;
          cached.src = next;
          const resume = this.looping.has(id) && !this.mutes[categoryForId(id)];
          try {
            audio.src = next;
            audio.load();
            if (resume) this.startElement(id, audio);
          } catch {
            cached.failed = true;
          }
          return;
        }
        this.warnOnce(id, `[audio] Failed to load "${id}" (${cached.src ?? src})`);
        cached.failed = true;
      });
      this.cache.set(id, cached);
    } catch (err) {
      this.warnOnce(id, `[audio] Audio() ctor threw for "${id}": ${String(err)}`);
      this.cache.set(id, { audio: null, failed: true });
    }
  }

  /** Warm the cache for a list of ids (or every manifest id when omitted). */
  preload(ids?: readonly string[]): void {
    for (const id of ids ?? Object.keys(this.manifest)) this.load(id);
  }

  // -------------------------------------------------------------------------
  // Playback
  // -------------------------------------------------------------------------

  /**
   * Fire-and-forget one-shot. Returns silently if the file is missing, the
   * category is muted, or audio isn't supported in this environment.
   */
  play(id: AudioId, opts?: PlayOptions): void {
    if (typeof window === 'undefined') return;
    const category = categoryForId(id);
    if (this.mutes[category]) return;

    const entry = this.manifest[id];
    const loop = opts?.loop ?? entry?.loop ?? false;

    // Throttle one-shots: the same sample can't retrigger inside its window.
    if (!loop) {
      const minInterval =
        opts?.minIntervalMs ?? entry?.minIntervalMs ?? DEFAULT_SFX_MIN_INTERVAL_MS;
      const now = nowMs();
      const last = this.lastPlayedAt.get(id);
      if (last !== undefined && now - last < minInterval) return;
      this.lastPlayedAt.set(id, now);
    }

    this.load(id);
    const cached = this.cache.get(id);
    if (!cached || cached.failed || !cached.audio) return;

    if (typeof opts?.volume === 'number') this.baseOverride.set(id, opts.volume);
    else this.baseOverride.delete(id);
    // An explicit play() always wins over a fade-out still in flight.
    this.clearFade(id);
    this.fadeGain.delete(id);

    const audio = cached.audio;
    audio.loop = loop;
    this.applyVolume(id);
    // Reset playback head so rapid-fire SFX aren't swallowed mid-play.
    // Music loops shouldn't be restarted by accident — guard with `loop`.
    if (!loop) {
      try {
        audio.currentTime = 0;
      } catch {
        // Seeking a not-yet-loaded clip throws in some browsers; play anyway.
      }
    }
    this.startElement(id, audio);
  }

  /** Call `audio.play()` and deal with rejections (autoplay policy, decode). */
  private startElement(id: string, audio: HTMLAudioElement): void {
    try {
      const result = audio.play();
      if (result && typeof result.catch === 'function') {
        result.catch((err: unknown) => {
          // Browsers reject play() before user-gesture; that's expected, not a bug.
          if (isAutoplayBlockedError(err)) {
            // A bed should start as soon as the user interacts; a one-shot
            // that missed its moment is simply dropped.
            if (isNotAllowedError(err) && this.looping.has(id)) this.queueForUnlock(id);
            return;
          }
          this.warnOnce(`play:${id}`, `[audio] play("${id}") rejected: ${String(err)}`);
        });
      }
    } catch (err) {
      this.warnOnce(`play:${id}`, `[audio] play("${id}") threw: ${String(err)}`);
    }
  }

  /**
   * Convenience for music beds. Sets `loop = true` and remembers the id so
   * un-muting can resume it. Idempotent: calling twice with the same id while
   * already playing leaves the bed running.
   */
  playLoop(id: AudioId, opts?: PlayOptions): void {
    this.looping.add(id);
    const cached = this.cache.get(id);
    // Don't restart an already-playing loop on subsequent calls.
    if (cached?.audio && !cached.audio.paused && cached.audio.loop) {
      // ...but rescue it if it was on its way out.
      if (this.fadeTimers.has(id) || this.fadeGain.has(id)) {
        this.clearFade(id);
        this.fadeGain.delete(id);
        this.applyVolume(id);
      }
      return;
    }
    this.play(id, { ...opts, loop: true });
  }

  /** Pause and rewind a clip. Removes it from the loop tracker. */
  stop(id: AudioId): void {
    this.looping.delete(id);
    this.pendingUnlock.delete(id);
    if (this.currentMusic === id) this.currentMusic = null;
    this.clearFade(id);
    this.fadeGain.delete(id);
    this.rewind(id);
  }

  // -------------------------------------------------------------------------
  // Music beds (crossfading)
  // -------------------------------------------------------------------------

  /**
   * Make `id` the one music bed: the previous bed fades out while this one
   * fades in. Idempotent — calling it again with the bed that is already
   * selected does nothing (it never restarts the track). Respects the music
   * mute (the bed starts when un-muted) and the autoplay policy (the bed
   * starts on the first user gesture).
   */
  playMusic(id: AudioId, opts?: MusicOptions): void {
    if (typeof window === 'undefined') return;
    const fadeMs = Math.max(0, opts?.fadeMs ?? DEFAULT_MUSIC_FADE_MS);
    const previous = this.currentMusic;

    if (previous === id) {
      // Same bed: make sure it is (still) on its way to full volume.
      this.playLoop(id, opts?.volume !== undefined ? { volume: opts.volume } : undefined);
      return;
    }
    if (previous) this.fadeOutAndStop(previous, fadeMs);
    this.currentMusic = id;

    const audio = this.cache.get(id)?.audio;
    const alreadyAudible = !!audio && !audio.paused && audio.loop;
    if (alreadyAudible) {
      // It was fading out from an earlier switch — turn it around in place.
      this.looping.add(id);
      this.fadeTo(id, 1, fadeMs);
      return;
    }
    this.playLoop(id, opts?.volume !== undefined ? { volume: opts.volume } : undefined);
    if (fadeMs > 0 && !this.mutes[categoryForId(id)]) {
      this.fadeGain.set(id, 0);
      this.applyVolume(id);
      this.fadeTo(id, 1, fadeMs);
    }
  }

  /** Fade the current bed out (if any) and forget it. */
  stopMusic(opts?: Pick<MusicOptions, 'fadeMs'>): void {
    const current = this.currentMusic;
    this.currentMusic = null;
    if (!current) return;
    this.fadeOutAndStop(current, Math.max(0, opts?.fadeMs ?? DEFAULT_MUSIC_FADE_MS));
  }

  /** The bed last requested through `playMusic()`, or null. */
  getCurrentMusic(): string | null {
    return this.currentMusic;
  }

  /** Fade a clip to silence, then pause + rewind it. */
  fadeOutAndStop(id: AudioId, fadeMs: number = DEFAULT_MUSIC_FADE_MS): void {
    this.looping.delete(id);
    this.pendingUnlock.delete(id);
    if (this.currentMusic === id) this.currentMusic = null;
    const audio = this.cache.get(id)?.audio;
    if (!audio || audio.paused || fadeMs <= 0) {
      this.clearFade(id);
      this.fadeGain.delete(id);
      this.rewind(id);
      return;
    }
    this.fadeTo(id, 0, fadeMs, () => {
      this.fadeGain.delete(id);
      this.rewind(id);
    });
  }

  /** Stop every currently-playing clip in the given category (or all). */
  stopAll(category?: AudioCategory): void {
    for (const [id] of this.cache.entries()) {
      if (category && categoryForId(id) !== category) continue;
      this.stop(id);
    }
    if (!category || category === 'music') this.currentMusic = null;
  }

  // -------------------------------------------------------------------------
  // Internal
  // -------------------------------------------------------------------------

  private applyVolumeToCachedAudio(category: AudioCategory): void {
    for (const [id] of this.cache.entries()) {
      if (categoryForId(id) !== category) continue;
      this.applyVolume(id);
    }
  }

  /** element volume = clip base × category volume × fade multiplier. */
  private applyVolume(id: string): void {
    const audio = this.cache.get(id)?.audio;
    if (!audio) return;
    const base = this.baseOverride.get(id) ?? this.manifest[id]?.volume ?? 1;
    const gain = this.fadeGain.get(id) ?? 1;
    audio.volume = clamp01(clamp01(base) * this.volumes[categoryForId(id)] * gain);
  }

  private rewind(id: string): void {
    const audio = this.cache.get(id)?.audio;
    if (!audio) return;
    try {
      audio.pause();
      audio.currentTime = 0;
    } catch {
      // Some browsers throw when seeking on a not-yet-loaded clip; swallow.
    }
  }

  private clearFade(id: string): void {
    const timer = this.fadeTimers.get(id);
    if (timer !== undefined) {
      clearInterval(timer);
      this.fadeTimers.delete(id);
    }
  }

  /** Linear ramp of the fade multiplier; `onDone` runs when the target is hit. */
  private fadeTo(id: string, target: number, ms: number, onDone?: () => void): void {
    this.clearFade(id);
    const from = this.fadeGain.get(id) ?? 1;
    if (ms <= 0 || from === target) {
      this.fadeGain.set(id, target);
      this.applyVolume(id);
      if (target === 1) this.fadeGain.delete(id);
      onDone?.();
      return;
    }
    const startedAt = nowMs();
    const timer = setInterval(() => {
      const t = Math.min(1, (nowMs() - startedAt) / ms);
      this.fadeGain.set(id, from + (target - from) * t);
      this.applyVolume(id);
      if (t >= 1) {
        this.clearFade(id);
        if (target === 1) this.fadeGain.delete(id);
        onDone?.();
      }
    }, FADE_STEP_MS);
    this.fadeTimers.set(id, timer);
  }

  // Autoplay policy -----------------------------------------------------------

  private queueForUnlock(id: string): void {
    this.pendingUnlock.add(id);
    if (this.unlockHandler || typeof window === 'undefined') return;
    const handler = () => {
      this.removeUnlockListeners();
      const pending = [...this.pendingUnlock];
      this.pendingUnlock.clear();
      for (const pendingId of pending) {
        if (!this.looping.has(pendingId)) continue;
        if (this.mutes[categoryForId(pendingId)]) continue;
        const audio = this.cache.get(pendingId)?.audio;
        if (!audio || !audio.paused) continue;
        audio.loop = true;
        this.applyVolume(pendingId);
        this.startElement(pendingId, audio);
      }
    };
    this.unlockHandler = handler;
    for (const type of UNLOCK_EVENTS) {
      window.addEventListener(type, handler, { capture: true, passive: true });
    }
  }

  private removeUnlockListeners(): void {
    const handler = this.unlockHandler;
    if (!handler || typeof window === 'undefined') return;
    this.unlockHandler = null;
    for (const type of UNLOCK_EVENTS) {
      window.removeEventListener(type, handler, { capture: true });
    }
  }

  private warnOnce(key: string, message: string): void {
    if (this.warned.has(key)) return;
    this.warned.add(key);
    // Devs want to see each unique audio issue exactly once. In production
    // the warning is pure noise — the runtime already no-ops the failed
    // clip via `cached.failed`, so swallowing it keeps consoles clean.
    if (process.env.NODE_ENV === 'production') return;
    console.warn(message);
  }
}

function isNotAllowedError(err: unknown): boolean {
  return !!err && typeof err === 'object' && (err as { name?: unknown }).name === 'NotAllowedError';
}

function isAutoplayBlockedError(err: unknown): boolean {
  if (!err || typeof err !== 'object') return false;
  const name = (err as { name?: unknown }).name;
  return name === 'NotAllowedError' || name === 'AbortError';
}

// ---------------------------------------------------------------------------
// Singleton accessor
// ---------------------------------------------------------------------------

let _manager: AudioManager | null = null;

/**
 * Lazily construct the singleton manager. Safe to call from SSR — the
 * manager itself just won't load anything until methods that touch
 * `window.Audio` are called.
 */
export function getAudioManager(): AudioManager {
  if (!_manager) {
    _manager = new AudioManager();
  }
  return _manager;
}

/**
 * Fetch the manifest from `/audio/manifest.json` and register it on the
 * singleton. Returns the parsed manifest (or an empty object on failure).
 * Failures are logged once and treated as "no manifest declared" — the rest
 * of the app keeps working, just without sound.
 */
export async function loadManifest(
  url = '/audio/manifest.json',
): Promise<AudioManifest> {
  if (typeof window === 'undefined') return {};
  try {
    // `no-cache` = revalidate: a redeploy with new sounds must not be masked
    // by a stale manifest from the HTTP cache.
    const res = await fetch(url, { cache: 'no-cache' });
    if (!res.ok) {
      console.warn(`[audio] Manifest fetch returned ${res.status} for ${url}`);
      return {};
    }
    const json = (await res.json()) as unknown;
    if (!json || typeof json !== 'object') {
      console.warn('[audio] Manifest is not an object');
      return {};
    }
    const manifest: AudioManifest = {};
    for (const [id, raw] of Object.entries(json as Record<string, unknown>)) {
      if (!raw || typeof raw !== 'object') continue;
      const entry = raw as Record<string, unknown>;
      if (typeof entry.src !== 'string') continue;
      const out: AudioManifestEntry = { src: entry.src };
      if (typeof entry.volume === 'number') out.volume = entry.volume;
      if (typeof entry.loop === 'boolean') out.loop = entry.loop;
      if (typeof entry.fallback === 'string') out.fallback = entry.fallback;
      if (typeof entry.minIntervalMs === 'number') out.minIntervalMs = entry.minIntervalMs;
      manifest[id] = out;
    }
    getAudioManager().registerManifest(manifest);
    return manifest;
  } catch (err) {
    console.warn(`[audio] Manifest load failed: ${String(err)}`);
    return {};
  }
}
