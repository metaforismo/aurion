// Generates packages/engine/src/territory/earthData.ts from the Natural
// Earth 1:110m countries shipped with `world-atlas`: for every country its
// ISO numeric id, its size relative to Italy, and its neighbours — the ones
// it shares a border with, plus the nearest ones across the water so islands
// are reachable.
//
// Run from apps/web (it uses that package's dependencies):
//   node ../../scripts/geo/build-earth-territories.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(`${process.cwd()}/`);
const { feature, neighbors } = require('topojson-client');
const { geoArea, geoCentroid, geoDistance } = require('d3-geo');

const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'));
const geometries = topo.objects.countries.geometries;
const features = feature(topo, topo.objects.countries).features;
const adjacency = neighbors(geometries);

const iso = (f) => (f.id === undefined || f.id === null ? null : String(f.id).padStart(3, '0'));
const ITALY = features.find((f) => iso(f) === '380');
const italyArea = geoArea(ITALY);
const EARTH_RADIUS_KM = 6371;
/** How far across the sea a territory can still be reached. */
const SEA_REACH_KM = 2200;
/** Sea links added per territory. */
const SEA_LINKS = 2;

const rows = features
  .map((f, i) => ({ f, i, id: iso(f) }))
  // Antarctica and features without an ISO code (disputed areas) are left out.
  .filter((r) => r.id && r.id !== '010');
const index = new Map(rows.map((r) => [r.i, r.id]));
const centroid = new Map(rows.map((r) => [r.id, geoCentroid(r.f)]));

const out = rows.map((r) => {
  const land = adjacency[r.i].map((j) => index.get(j)).filter(Boolean);
  const sea = rows
    .filter((o) => o.id !== r.id && !land.includes(o.id))
    .map((o) => ({ id: o.id, km: geoDistance(centroid.get(r.id), centroid.get(o.id)) * EARTH_RADIUS_KM }))
    .sort((a, b) => a.km - b.km)
    // Within reach — or, for a territory with no land border at all, simply
    // the nearest ones, so nowhere is cut off.
    .filter((o, k) => o.km <= SEA_REACH_KM || (land.length === 0 && k < SEA_LINKS))
    .slice(0, SEA_LINKS)
    .map((o) => o.id);
  const weight = Math.min(3, Math.max(0.4, Math.sqrt(geoArea(r.f) / italyArea)));
  return { id: r.id, name: r.f.properties.name, weight: Number(weight.toFixed(2)), neighbours: [...land, ...sea] };
});

// Links must work both ways.
const byId = new Map(out.map((t) => [t.id, t]));
for (const t of out) for (const n of t.neighbours) if (!byId.get(n).neighbours.includes(t.id)) byId.get(n).neighbours.push(t.id);
out.sort((a, b) => a.id.localeCompare(b.id));
for (const t of out) t.neighbours.sort();

const body = out
  .map((t) => `  { id: '${t.id}', name: ${JSON.stringify(t.name)}, weight: ${t.weight}, neighbours: [${t.neighbours.map((n) => `'${n}'`).join(', ')}] },`)
  .join('\n');
writeFileSync(
  new URL('../../packages/engine/src/territory/earthData.ts', import.meta.url),
  `// GENERATED by scripts/geo/build-earth-territories.mjs — do not edit by hand.
// Source: Natural Earth 1:110m countries (public domain), via world-atlas.

export type EarthTerritory = {
  /** ISO 3166-1 numeric code, zero-padded. */
  id: string;
  /** English short name, for logs and tests; the UI localises by id. */
  name: string;
  /** Size relative to Italy (square root of the area ratio), clamped to 0.4..3. */
  weight: number;
  /** Land neighbours, plus the nearest territories across the sea. */
  neighbours: string[];
};

export const EARTH_TERRITORIES: readonly EarthTerritory[] = [
${body}
];
`,
);
console.log(`${out.length} territories written`);
